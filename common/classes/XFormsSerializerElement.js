import { TEXT_NODE, xhtmlURI, xmlSchemaURI, xformsURI, svgURI } from "../utils/constants.js";
import { encodeEntities } from "../utils/encodeEntities.js";
import { XFormsSerializerAttribute } from "./XFormsSerializerAttribute.js";

const autoclose = new Set([
  'area',
  'base',
  'br',
  'col',
  'embed',
  'hr',
  'img',
  'input',
  'link',
  'meta',
  'param',
  'source',
  'track',
  'wbr'
]);
const tableElements = new Set([
  'table',
  'thead',
  'tbody',
  'tfoot'
]);
const svgTextElements = new Set([
  'text',
  'tspan',
  'textPath',
  'tref'
]);

export class XFormsSerializerElement {
  textContent = '';
  attributes = [];
  childNodes = [];
  mixedContent = false;
  avt = false;
  constructor(namespaceURI, qualifiedName, ownerDocument) {
    this.ownerDocument = ownerDocument;
    this.xmlElement = this.ownerDocument.xmlPart;
    if (namespaceURI === xformsURI && !this.ownerDocument.xmlPart) {
      this.namespaceURI = xhtmlURI;
      const parts = qualifiedName.split(':');
      this.prefix = '';
      this.localName = 'xforms-' + (parts.length > 1 ? parts[1] : parts[0]).toLowerCase();
      this.nodeName = this.localName;
      if (this.localName === 'xforms-instance') {
        this.ownerDocument.xmlPart = true;
      }
    } else if (namespaceURI === xhtmlURI && !this.ownerDocument.xmlPart) {
      this.namespaceURI = namespaceURI;
      const parts = qualifiedName.split(':');
      this.prefix = '';
      this.localName = (parts.length > 1 ? parts[1] : parts[0]).toLowerCase();
      this.nodeName = this.localName;
      if (this.localName === 'head') {
        const meta = this.ownerDocument.createElement('meta');
        meta.setAttribute('http-equiv', 'Content-Type');
        meta.setAttribute('content', 'text/html;charset=utf-8');
        this.childNodes.push(meta);
      } else if (this.localName === 'html') {
        const comment = this.ownerDocument.createComment(' HTML elements generated by XSLTForms 1.8 (665) [xsltforms-xsl.js] - Copyright (C) 2025 <agenceXML> - Alain Couthures - https://www.agencexml.com ');
        this.childNodes.push(comment);
      }
    } else {
      this.nodeName = qualifiedName;
      if (namespaceURI) {
        this.namespaceURI = namespaceURI;
        const parts = qualifiedName.split(':');
        this.prefix = parts.length > 1 ? parts[0] : '';
        this.localName = parts.length > 1 ? parts[1] : parts[0];
        this.xmlElement = true;
        if (this.namespaceURI === xmlSchemaURI) {
          this.ownerDocument.xmlPart = true;
        }
      } else {
        this.namespaceURI = '';
        this.prefix = '';
        this.localName = qualifiedName;
      }
    }
  }
  serialize(offset = '', spaces = '') {
    if (this.nodeName) {
      let s = offset +'<' + this.nodeName;
      if (this.attributes.length !== 0) {
        const namespaceDeclarations = [];
        const otherAttributes = [];
        this.attributes.forEach(attr => {
          if (attr.name === 'xmlns') {
            if (this.xmlElement || attr.value !== 'http://www.w3.org/1999/xhtml') {
              namespaceDeclarations.unshift(attr);
            }
          } else if (attr.name.startsWith('xmlns:')) {
            if (this.xmlElement || attr.value !== 'http://www.w3.org/1999/xhtml') {
              namespaceDeclarations.push(attr);
            }
          } else {
            otherAttributes.push(attr);
          }
        });
        namespaceDeclarations.sort((a, b) => a.name === 'xmlns' ? -1 : b.name === 'xmlns' ? 1 : a.name.localeCompare(b.name));
        otherAttributes.sort((a, b) => {
          const aParts = a.name.split(':');
          const bParts = b.name.split(':');
          const aPrefix = aParts.length > 1 ? aParts[0] : '';
          const aLocalName = aParts.length > 1 ? aParts[1] : aParts[0];
          const bPrefix = bParts.length > 1 ? bParts[0] : '';
          const bLocalName = bParts.length > 1 ? bParts[1] : bParts[0];
          return aPrefix < bPrefix ? -1 : aPrefix > bPrefix ? 1 : aLocalName.localeCompare(bLocalName);
        });
        for (let i = 0, l = namespaceDeclarations.length; i < l; i++) {
          s += ' ' + namespaceDeclarations[i].name + '="' + encodeEntities(namespaceDeclarations[i].value) + '"';
        }
        for (let i = 0, l = otherAttributes.length; i < l; i++) {
          const value = otherAttributes[i].value;
          s += ' ' + otherAttributes[i].name + (value ? '="' + encodeEntities(value) + '"' : '');
        }
      }
      if (this.childNodes.length !== 0) {
        s += '>';
        if (this.mixedContent || !this.ownerDocument.indent) {
          for (const child of this.childNodes) {
            s += child.serialize();
          }
        } else {
          for (const child of this.childNodes) {
            if (this.ownerDocument.indent && (child.nodeType !== TEXT_NODE || child.textContent.trim() !== '')) {
              s += child.serialize(offset + spaces, spaces);
            }
          }
        }
        s += (this.mixedContent ? '' : offset) + '</' + this.nodeName + '>';
      } else if (autoclose.has(this.nodeName) && !this.xmlElement) {
        s += '>';
      } else if (this.xmlElement) {
        s += '/>';
      } else {
        s += '></' + this.nodeName + '>';
      }
      return s;
    }
    return '';
  }
  appendChild(node) {
    this.mixedContent |= node.nodeType === TEXT_NODE && node.textContent.trim() !== '';
    if (this.nodeName === 'xforms-instance') {
      if (!this.script) {
        this.script = this.ownerDocument.createElement('script');
        this.script.setAttribute('type', 'application/xml');
        this.childNodes.push(this.script);
      }
      this.script.childNodes.push(node);
    } else if (this.nodeName === 'xforms-model') {
      this.ownerDocument.xmlPart = false;
      if (node.namespaceURI === xmlSchemaURI) {
        this.script = this.ownerDocument.createElement('script');
        this.script.setAttribute('type', 'application/xml');
        this.script.childNodes.push(node);
        this.childNodes.push(this.script);
      } else {
        this.childNodes.push(node);
      }
    } else if (node.nodeName === 'xforms-model') {
      this.ownerDocument.models.push(node);
    } else if (this.nodeName === 'head') {
      if (node.nodeName !== 'meta') {
        this.ownerDocument.afterMetas.push(node);
      } else if (node.getAttribute('http-equiv') !== 'Content-Type') {
        this.childNodes.push(node);
      }
    } else if (node.nodeName === 'head') {
      const link = this.ownerDocument.createElement('link');
      link.setAttribute('href', this.ownerDocument.path + 'xsltforms.css');
      link.setAttribute('rel', 'stylesheet');
      link.setAttribute('type', 'text/css');
      node.childNodes.push(link);
      node.childNodes.push(...this.ownerDocument.afterMetas);
      const script = this.ownerDocument.createElement('script');
      script.setAttribute('src', this.ownerDocument.path + 'xsltforms.js');
      script.setAttribute('type', 'text/javascript');
      script.setAttribute('id', 'xsltforms-src');
      script.setAttribute('data-uri', 'http://www.agencexml.com/xsltforms');
      script.setAttribute('data-version', '664');
      script.mixedContent = true;
      const comment = this.ownerDocument.createTextNode('//');
      script.childNodes.push(comment);
      node.childNodes.push(script);
      this.childNodes.push(node);
    } else if (node.nodeName === 'xforms-repeat' && tableElements.has(this.nodeName)) {
      for (const attr of node.attributes) {
        if (attr.name.startsWith('xf-')) {
          this.setAttribute('xf-repeat-' + attr.name.substring(3), attr.value);
        } else {
          this.setAttribute(attr.name, attr.value);
        }
      }
      this.childNodes.push(...node.childNodes);
    } else if (this.nodeName === 'body') {
      if (!this.form) {
        this.form = this.ownerDocument.createElement('form');
        const xforms_body = this.ownerDocument.createElement('xforms-body');
        xforms_body.childNodes.push(this.form);
        const xforms_form = this.ownerDocument.createElement('xforms-form');
        if (this.ownerDocument.options.length > 0) {
          const xforms_options = this.ownerDocument.createElement('xforms-options');
          xforms_options.attributes = this.ownerDocument.options;
          xforms_form.childNodes.push(xforms_options);
        }
        xforms_form.childNodes.push(...this.ownerDocument.models);
        xforms_form.childNodes.push(xforms_body);
        this.childNodes.push(xforms_form);
      }
      this.form.childNodes.push(node);
    } else if (this.namespaceURI === svgURI && this.localName !== 'foreignObject') {
      const replaceCustomElements = (svgElement, nodes) => {
        const svgChildName = svgTextElements.has(svgElement.localName) ? 'tspan' : 'g';
        for (const n of nodes) {
          if (n.nodeName?.startsWith('xforms-')) {
            n.setAttribute('xforms-name', n.nodeName.substring(7));
            n.localName = svgChildName;
            n.namespaceURI = svgURI;
            if (svgElement.prefix) {
              n.prefix = svgElement.prefix;
              n.nodeName = svgElement.prefix + ':' + svgChildName;
            } else {
              n.prefix = '';
              n.nodeName = svgChildName;
            }
            replaceCustomElements(n, n.childNodes);
          }
        }
      }
      replaceCustomElements(this, [node]);
      this.childNodes.push(node);
    } else {
      this.childNodes.push(node);
    }
  }
  getAttribute(attrname) {
    for (let i = 0, l = this.attributes.length; i < l; i++) {
      if (this.attributes[i].name === attrname) {
        return this.attributes[i].value;
      }
    }
    return '';
  }
  getAttributeNS(namespaceURI, qualifiedName) {
    const parts = qualifiedName.split(':');
    const localName = parts.length > 1 ? parts[1] : parts[0];
    for (let i = 0, l = this.attributes.length; i < l; i++) {
      if (this.attributes[i].namespaceURI === namespaceURI && this.attributes[i].localName === localName) {
        return this.attributes[i].value;
      }
    }
    return '';
  }
  setAttribute(name, value) {
    this.setAttributeNS('', name, value);
  }
  setAttributeNS(namespaceURI, qualifiedName, value) {
    if (this.nodeName !== 'body' || qualifiedName !== 'onload') {
      const parts = qualifiedName.split(':');
      const localName = parts.length > 1 ? parts[1] : parts[0];
      for (let i = 0, l = this.attributes.length; i < l; i++) {
        if (this.attributes[i].namespaceURI === namespaceURI && this.attributes[i].localName === localName) {
          this.attributes[i].value = value;
          return;
        }
      }
      const attr = new XFormsSerializerAttribute(namespaceURI, qualifiedName, value, this);
      this.attributes.push(attr);
    }
  }
  setAttributeNodeNS(attr) {
    this.attributes.push(attr);
  }
}